// 한국어 주석: 앱 전체에서 사용하는 간격 상수 정의
/// App-wide spacing constants following Material Design 3 guidelines

class AppSpacing {
  AppSpacing._(); // Private constructor to prevent instantiation

  // Base spacing unit (4dp)
  static const double xs = 4.0;
  static const double sm = 8.0;
  static const double md = 16.0;
  static const double lg = 24.0;
  static const double xl = 32.0;
  static const double xxl = 48.0;

  // Specific spacing
  static const double cardMargin = 8.0; // 카드 마진
  static const double cardPadding = 16.0; // 카드 패딩
  static const double screenPadding = 16.0; // 화면 기본 패딩
  static const double buttonHeight = 48.0; // 버튼 높이
  static const double iconSize = 24.0; // 아이콘 크기
  static const double iconSizeSmall = 20.0; // 작은 아이콘 크기
  static const double iconSizeLarge = 32.0; // 큰 아이콘 크기
}

